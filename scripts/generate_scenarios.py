from __future__ import annotations

import json
from pathlib import Path

import cv2

from examples.synthetic import make_gauge


OUT = Path(__file__).resolve().parents[1] / "frontend" / "public" / "scenarios"


def save(name: str, image: object) -> None:
    target = OUT / f"{name}.png"
    if not cv2.imwrite(str(target), image):
        raise RuntimeError(f"Could not write {target}")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    clear = make_gauge(0.63, seed=17)
    glare = make_gauge(0.63, seed=17, glare=True)
    multi = make_gauge(0.30, seed=23, second_pointer_fraction=0.78)
    save("clear", clear.image)
    save("glare", glare.image)
    save("contradictory", multi.image)

    unsupported = clear.image.copy()
    unsupported[:] = (230, 233, 232)
    cv2.rectangle(unsupported, (112, 150), (528, 488), (48, 58, 63), 8, cv2.LINE_AA)
    cv2.rectangle(unsupported, (128, 166), (512, 472), (243, 245, 244), -1, cv2.LINE_AA)
    cv2.putText(unsupported, "DIGITAL METER", (176, 275), cv2.FONT_HERSHEY_SIMPLEX, 1.1, (60, 70, 75), 2, cv2.LINE_AA)
    cv2.putText(unsupported, "12.4", (214, 365), cv2.FONT_HERSHEY_SIMPLEX, 2.0, (30, 48, 58), 4, cv2.LINE_AA)
    save("unsupported", unsupported)

    manifest = {
        "source": "Generated by examples/synthetic.py in this repository; no external image assets.",
        "license": "CC0-1.0",
        "synthetic": True,
        "scenarios": [
            {"id": "clear", "title": "Clear circular gauge", "image": "/scenarios/clear.png", "expected_behavior": "Assess image quality and return an evidence-backed result only if the independent estimates pass the policy.", "synthetic_truth": {"reading": 63.0, "units": "psi"}},
            {"id": "glare", "title": "Localized glass glare", "image": "/scenarios/glare.png", "expected_behavior": "Identify the clipped reflection and request a new user-captured view before measuring.", "synthetic_truth": {"reading": 63.0, "units": "psi"}},
            {"id": "contradictory", "title": "Two-pointer ambiguity", "image": "/scenarios/contradictory.png", "expected_behavior": "The image violates the single-pointer scope; estimator disagreement must trigger a new view or human review, never a confident value.", "synthetic_truth": None},
            {"id": "unsupported", "title": "Unsupported digital meter", "image": "/scenarios/unsupported.png", "expected_behavior": "Decline the unsupported instrument rather than interpreting its digits as an analog dial.", "synthetic_truth": None},
        ],
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
